/** Город по названию региона, без учёта регистра и «г.». */
export function cityCoords(region: string): [number, number] | null {
  const name = region.replace(/^г\.?\s*/i, '').trim().toLowerCase()
  const found = Object.entries(CITIES).find(([city]) => city.toLowerCase() === name)
  return found ? found[1] : null
}
